import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { writeGenerated } from './write-generated.mjs';
import { z } from 'zod';
import { labSchema } from '../src/lab-schemas.mjs';
import { templateSchema } from '../src/template-schemas.mjs';
await writeGenerated('vmware-workstation/templates/schema-v1.json', JSON.stringify(z.toJSONSchema(templateSchema), null, 2) + '\n');
await writeGenerated('vmware-workstation/labs/schema-v1.json', JSON.stringify(z.toJSONSchema(labSchema, { io: 'input' }), null, 2) + '\n');
const require = createRequire(import.meta.url);
// SDK 1.x imports AJV as its default even when given a validator. Use its
// interpreted provider for the standalone server and diagnostic bundles.
const interpretedSdkValidation = {
  name: 'interpreted-sdk-validation',
  setup(build) {
    build.onResolve({ filter: /^\.\.\/validation\/ajv-provider\.js$/ }, args => {
      if (/[\\/]node_modules[\\/]@modelcontextprotocol[\\/]sdk[\\/]dist[\\/]/.test(args.importer)) {
        return { path: 'sdk-default-json-schema-validator', namespace: 'interpreted-sdk-validation' };
      }
    });
    build.onLoad({ filter: /^sdk-default-json-schema-validator$/, namespace: 'interpreted-sdk-validation' }, () => ({
      contents: `export { CfWorkerJsonSchemaValidator as AjvJsonSchemaValidator } from '@modelcontextprotocol/sdk/validation/cfworker';`,
      resolveDir: path.dirname(require.resolve('@modelcontextprotocol/sdk/validation/cfworker')),
    }));
  },
};
const result = await build({
  entryPoints: ['src/server.mjs', 'src/claude-desktop.mjs', 'src/inspect-catalog.mjs', 'src/configure-console.mjs', 'src/set-credentials.mjs'], outdir: 'vmware-workstation/server', outExtension: { '.js': '.cjs' },
  bundle: true, platform: 'node', target: 'node22', format: 'cjs',
  metafile: true, write: false, plugins: [interpretedSdkValidation],
  banner: { js: '// Generated by npm run build. Edit src/ and rebuild.' },
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (match) packages.add(match[1]);
}
if (packages.has('ajv') || !packages.has('@cfworker/json-schema')) throw new Error('Bundles must use the interpreted MCP SDK validator');
for (const output of result.outputFiles) await writeGenerated(output.path, output.contents);
let notices = '# Bundled third-party licenses\n\n';
for (const name of [...packages].sort()) {
  const root = path.join('node_modules', name);
  const metadata = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
  const licenses = (await fs.readdir(root)).filter(file => /^(license|copying)(\.|$)/i.test(file)).map(file => path.join(root, file));
  // The upstream npm tarball omits its repository's MIT license.
  if (name === '@cfworker/json-schema' && metadata.version === '4.1.6' && !licenses.length) {
    licenses.push('scripts/licenses/cfworker-json-schema-4.1.6.txt');
  }
  if (!licenses.length) throw new Error(`No license file found for bundled dependency ${name}`);
  notices += `## ${name} ${metadata.version}\n\n`;
  for (const file of licenses) notices += `${await fs.readFile(file, 'utf8')}\n\n`;
}
await writeGenerated('vmware-workstation/THIRD-PARTY-NOTICES.md', notices.trimEnd() + '\n');
await writeGenerated('vmware-workstation/LICENSE', await fs.readFile('LICENSE'));
await import('./generate-reference.mjs');
await import('./generate-client-metadata.mjs');
