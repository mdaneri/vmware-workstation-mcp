import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { writeGenerated } from './write-generated.mjs';
import { z } from 'zod';
import { labSchema } from '../src/lab-schemas.mjs';
import { templateSchema } from '../src/template-schemas.mjs';
await writeGenerated('vmware-workstation/templates/schema-v1.json', JSON.stringify(z.toJSONSchema(templateSchema), null, 2) + '\n');
await writeGenerated('vmware-workstation/labs/schema-v1.json', JSON.stringify(z.toJSONSchema(labSchema, { io: 'input' }), null, 2) + '\n');
const result = await build({
  entryPoints: ['src/server.mjs', 'src/inspect-catalog.mjs', 'src/configure-console.mjs', 'src/set-credentials.mjs'], outdir: 'vmware-workstation/server', outExtension: { '.js': '.cjs' },
  bundle: true, platform: 'node', target: 'node22', format: 'cjs',
  metafile: true, write: false,
  banner: { js: '// Generated by npm run build. Edit src/ and rebuild.' },
});
for (const output of result.outputFiles) await writeGenerated(output.path, output.contents);
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (match) packages.add(match[1]);
}
let notices = '# Bundled third-party licenses\n\n';
for (const name of [...packages].sort()) {
  const root = path.join('node_modules', name);
  const metadata = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
  const licenses = (await fs.readdir(root)).filter(file => /^(license|copying)(\.|$)/i.test(file));
  if (!licenses.length) throw new Error(`No license file found for bundled dependency ${name}`);
  notices += `## ${name} ${metadata.version}\n\n`;
  for (const file of licenses) notices += `${await fs.readFile(path.join(root, file), 'utf8')}\n\n`;
}
await writeGenerated('vmware-workstation/THIRD-PARTY-NOTICES.md', notices.trimEnd() + '\n');
await writeGenerated('vmware-workstation/LICENSE', await fs.readFile('LICENSE'));
await import('./generate-reference.mjs');
